"""Where jobs run: the execution seam.

A job is rendered once into a bash script that both adapters run unchanged: the
SLURM adapter submits it with sbatch, the local adapter runs it with bash in the
foreground (bash reads the #SBATCH lines as comments). What the script runs in is
the job's runtime: an Apptainer image, a Python venv (with the site's modules), or
the host as is.
"""

import re
import shlex
import subprocess
import sys
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

from heron.errors import HeronConfigError
from heron.site import Site

RUNTIMES = ("apptainer", "venv", "host")


class JobFailed(RuntimeError):
    """A job run by the local adapter exited with an error."""


@dataclass(frozen=True)
class Job:
    name: str
    log_dir: Path
    log_stem: str                    # logs: <log_dir>/<log_stem>_<job id>.out / .err
    command: str                     # the shell command, run inside the runtime
    runtime: str                     # apptainer | venv | host
    resources: dict                  # time, mem, cpus, gpus
    image: Path | None = None        # apptainer runtime only
    binds: tuple = ()                # apptainer runtime only: mounted at the same path
    env: dict = field(default_factory=dict)

    @property
    def gpu(self) -> bool:
        return int(self.resources.get("gpus", 0)) > 0


def render(job: Job, site: Site) -> str:
    """The job's bash script, for either adapter."""
    if job.runtime not in RUNTIMES:
        raise HeronConfigError(f"unknown runtime {job.runtime!r}")
    r = job.resources
    lines = [
        "#!/bin/bash",
        f"#SBATCH --job-name={job.name}",
        f"#SBATCH --output={job.log_dir}/{job.log_stem}_%j.out",
        f"#SBATCH --error={job.log_dir}/{job.log_stem}_%j.err",
        f"#SBATCH --time={r['time']}",
        f"#SBATCH --mem={r['mem']}",
    ]
    if job.gpu:
        lines.append(f"#SBATCH --gpus-per-node={r['gpus']}")
    lines += [
        f"#SBATCH --cpus-per-task={r['cpus']}",
        "#SBATCH --export=ALL,DISABLE_DCGM=1",
        "# Generated by heron. Submitted with sbatch, or run with bash (the #SBATCH lines are",
        "# comments to bash). Paths are the same on the host and in the container.",
        "set -e",
    ]
    # host jobs run heron's own Python (sys.executable), so they need the venv's modules too.
    lines += [f"module load {m}" for m in site.modules_for("venv" if job.runtime == "host" else job.runtime)]
    env = " ".join(f"{k}={shlex.quote(str(v))}" for k, v in job.env.items())
    if job.runtime == "apptainer":
        if job.image is None:
            raise HeronConfigError(f"job {job.name}: the apptainer runtime needs an image")
        binds = " ".join(f"--bind {shlex.quote(str(b))}" for b in job.binds)
        nv = " --nv" if job.gpu else ""
        lines.append(f"apptainer exec -C{nv} {binds} {shlex.quote(str(job.image))} \\")
        lines.append(f"    {'env ' + env + ' ' if env else ''}{job.command}")
    else:
        if job.runtime == "venv":
            lines.append(f"source {shlex.quote(str(site.venv / 'bin' / 'activate'))}")
        lines += [f"export {k}={shlex.quote(str(v))}" for k, v in job.env.items()]
        lines.append(job.command)
    return "\n".join(lines) + "\n"


class SlurmExecutor:
    """Submits job scripts with sbatch. `after` makes a job wait for another's success."""
    name = "slurm"

    def __init__(self, site: Site, account: str | None = None):
        self.site = site
        self.account_override = account

    def command(self, script: Path, gpu: bool, after: str | None = None) -> list[str]:
        account = self.account_override or self.site.account(gpu)
        return (["sbatch"] + ([f"--account={account}"] if account else [])
                + ([f"--dependency=afterok:{after}"] if after else []) + [str(script)])

    def submit(self, script: Path, gpu: bool, log_dir: Path, log_stem: str, after: str | None = None) -> str:
        log_dir.mkdir(parents=True, exist_ok=True)
        out = subprocess.run(self.command(script, gpu, after), capture_output=True, text=True, check=True).stdout
        match = re.search(r"Submitted batch job (\d+)", out)
        return match.group(1) if match else out.strip()


class LocalExecutor:
    """Runs job scripts here, in the foreground, one after another.

    Output goes to the terminal and to <log_dir>/<log_stem>_local-<time>.out. A failed
    job raises JobFailed, so a job meant to run `after` it is never started.
    """
    name = "local"

    def __init__(self, site: Site):
        self.site = site

    def submit(self, script: Path, gpu: bool, log_dir: Path, log_stem: str, after: str | None = None) -> str:
        job_id = f"local-{datetime.now():%Y%m%d_%H%M%S}"
        log_dir.mkdir(parents=True, exist_ok=True)
        log = log_dir / f"{log_stem}_{job_id}.out"
        with open(log, "w") as out:
            proc = subprocess.Popen(["bash", str(script)], stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                    text=True, bufsize=1)
            for line in proc.stdout:
                sys.stdout.write(line)
                out.write(line)
            code = proc.wait()
        if code != 0:
            raise JobFailed(f"{script} exited with {code}; log: {log}")
        return job_id


def executor(site: Site, account: str | None = None):
    return LocalExecutor(site) if site.scheduler == "local" else SlurmExecutor(site, account)


def venv_has(venv: Path, package: str) -> bool:
    """Whether a venv has a package installed, without starting its Python."""
    return any(venv.glob(f"lib/python3*/site-packages/{package}"))
